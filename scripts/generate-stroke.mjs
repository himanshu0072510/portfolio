#!/usr/bin/env node
/**
 * Generates the variable-width nib stroke used in the hero.
 *
 * A real pen stroke is not a constant-width line: it is thin where the nib
 * lands, swells as pressure builds, and tapers as it lifts. This samples a
 * cubic Bezier, offsets the curve along its normals by a width profile, and
 * emits a closed outline that can be filled.
 *
 *   node scripts/generate-stroke.mjs
 */
import { writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(__dirname, '../src/components/stroke.generated.ts')

// The centreline of the stroke, in a 260x150 viewBox.
const P0 = [16, 116]
const P1 = [64, 58]
const P2 = [104, 104]
const P3 = [148, 62]
const P4 = [196, 22]
const P5 = [244, 48]

// Cubic segments: [p0, p1, p2, p3] using P0..P5 as two joined cubics.
const SEGMENTS = [
  [P0, P1, P2, P3],
  [P3, P4, P5, [250, 40]],
]

const SAMPLES = 160

function cubicAt(p0, p1, p2, p3, t) {
  const u = 1 - t
  const a = u * u * u
  const b = 3 * u * u * t
  const c = 3 * u * t * t
  const d = t * t * t
  return [
    a * p0[0] + b * p1[0] + c * p2[0] + d * p3[0],
    a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1],
  ]
}

function cubicTangent(p0, p1, p2, p3, t) {
  const u = 1 - t
  const x = 3 * u * u * (p1[0] - p0[0]) + 6 * u * t * (p2[0] - p1[0]) + 3 * t * t * (p3[0] - p2[0])
  const y = 3 * u * u * (p1[1] - p0[1]) + 6 * u * t * (p2[1] - p1[1]) + 3 * t * t * (p3[1] - p2[1])
  const len = Math.hypot(x, y) || 1
  return [x / len, y / len]
}

/**
 * Width profile across the stroke: lands thin, swells through the belly,
 * tapers at the lift. Slightly front-loaded so the stroke looks written,
 * not extruded.
 */
function widthAt(t) {
  const base = 3.2
  const peak = 15.5
  const swell = Math.sin(Math.PI * Math.pow(t, 0.86))
  return base + (peak - base) * Math.pow(swell, 0.72)
}

const left = []
const right = []

for (let s = 0; s < SEGMENTS.length; s++) {
  const [p0, p1, p2, p3] = SEGMENTS[s]
  const steps = Math.round(SAMPLES / SEGMENTS.length)
  for (let i = 0; i <= steps; i++) {
    const local = i / steps
    const [x, y] = cubicAt(p0, p1, p2, p3, local)
    const [tx, ty] = cubicTangent(p0, p1, p2, p3, local)
    const nx = -ty
    const ny = tx
    // Global progress across the whole stroke for the width profile.
    const global = (s + local) / SEGMENTS.length
    const w = widthAt(global) / 2
    left.push([x + nx * w, y + ny * w])
    right.push([x - nx * w, y - ny * w])
  }
}

function fmt(n) {
  return Number(n.toFixed(2)).toString()
}

function toPath(points) {
  return points.map(([x, y], i) => `${i === 0 ? 'M' : 'L'}${fmt(x)} ${fmt(y)}`).join(' ')
}

// Outline: down one side, back along the other.
const outline = `${toPath(left)} ${toPath([...right].reverse()).replace('M', 'L')} Z`
const centreline = SEGMENTS.map(([p0, p1, p2, p3], i) =>
  i === 0
    ? `M${fmt(p0[0])} ${fmt(p0[1])} C${fmt(p1[0])} ${fmt(p1[1])} ${fmt(p2[0])} ${fmt(p2[1])} ${fmt(p3[0])} ${fmt(p3[1])}`
    : `C${fmt(p1[0])} ${fmt(p1[1])} ${fmt(p2[0])} ${fmt(p2[1])} ${fmt(p3[0])} ${fmt(p3[1])}`,
).join(' ')

const content = `/**
 * Generated by scripts/generate-stroke.mjs — do not hand-edit.
 *
 * A variable-width nib stroke: thin where the nib lands, swelling through
 * the belly, tapering at the lift.
 */

/** Closed outline of the stroke, to be filled. */
export const STROKE_OUTLINE = '${outline}'

/** The centreline, used to drive the travelling nib. */
export const STROKE_CENTRELINE = '${centreline}'

/** ViewBox of the drawing. */
export const STROKE_VIEWBOX = '0 0 260 150'
`

await writeFile(OUT, content)
console.log(`✓ wrote ${OUT}`)
console.log(`  outline  : ${outline.length} chars`)
console.log(`  centreline: ${centreline}`)
